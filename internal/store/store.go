// Package store is DockFleet's persistence layer.
//
// State is split by who owns it:
//
//   - Desired state is what administrators asked for: services and their
//     revisions, the replica count, workload placements and their desired
//     state, and enrollments. Only the manager changes it, on behalf of an
//     administrator (or, later, a reconciler acting on their intent).
//   - Observed state is what agents reported: nodes (identity, declared
//     capacity, heartbeats) and workload observations. Only the manager
//     changes it, on behalf of an agent.
//
// The two never share a column or a write path, so a late or lost report can
// never overwrite intent, and intent never passes for a fact. Reading a
// workload returns both, side by side, in separate fields.
//
// The layer is a set of small repository interfaces. Store combines them and
// adds transactions. Postgres and Memory implement it and are held to one
// conformance suite.
package store

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"time"
)

var (
	ErrNotFound = errors.New("not found")
	ErrConflict = errors.New("already exists")
	// ErrVersionConflict means an optimistic-lock check failed: the record
	// changed since the caller read it. Read it again and retry.
	ErrVersionConflict = errors.New("the record was changed concurrently")
	// ErrUnchanged means the requested change equals the current state, so
	// nothing was written (no new version, no new revision).
	ErrUnchanged = errors.New("nothing to change")
	// ErrInvalid means a value violates a rule the store enforces.
	ErrInvalid = errors.New("invalid value")
	// ErrLeaseHeld means another holder owns an unexpired lease.
	ErrLeaseHeld = errors.New("lease is held by another manager")
)

// Observed workload phases. WorkloadScheduled is never stored: it is what
// Workload.Phase reports until the node's agent has reported anything.
const (
	WorkloadScheduled = "scheduled"
	WorkloadPending   = "pending"
	WorkloadRunning   = "running"
	WorkloadSucceeded = "succeeded"
	WorkloadFailed    = "failed"
	WorkloadStopped   = "stopped"
)

// Desired workload states.
const (
	DesiredRunning = "running"
	DesiredStopped = "stopped"
)

// ValidObservedState reports whether s can be stored as an observed phase.
func ValidObservedState(s string) bool {
	switch s {
	case WorkloadPending, WorkloadRunning, WorkloadSucceeded, WorkloadFailed, WorkloadStopped:
		return true
	}
	return false
}

// ValidDesiredState reports whether s is a desired workload state.
func ValidDesiredState(s string) bool {
	return s == DesiredRunning || s == DesiredStopped
}

var namePattern = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]{0,62}$`)

// ValidName reports whether s is acceptable as a node ID, service or workload
// name, manager ID or lease name.
func ValidName(s string) bool {
	return namePattern.MatchString(s)
}

// NewID returns a random identifier. IDs are generated by the caller, never by
// a database sequence, so any number of managers can create records without
// coordinating.
func NewID() string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		panic("store: no randomness available: " + err.Error())
	}
	return hex.EncodeToString(b)
}

// Node is what an agent told the manager about itself: observed state.
type Node struct {
	ID            string            `json:"id"`
	Name          string            `json:"name"`
	CPUMillis     int64             `json:"cpu_millis"`
	MemoryBytes   int64             `json:"memory_bytes"`
	Labels        map[string]string `json:"labels"`
	AgentVersion  string            `json:"agent_version"`
	RegisteredAt  time.Time         `json:"registered_at"`
	LastHeartbeat time.Time         `json:"last_heartbeat"`
}

// Enrollment is an administrator's explicit permission for a node ID to join
// the fleet (desired state). Only enrolled nodes may register; revoking blocks
// a node again.
type Enrollment struct {
	NodeID      string     `json:"node_id"`
	Description string     `json:"description"`
	CreatedAt   time.Time  `json:"created_at"`
	RevokedAt   *time.Time `json:"revoked_at,omitempty"`
}

// Active reports whether the enrollment has not been revoked.
func (e Enrollment) Active() bool {
	return e.RevokedAt == nil
}

// Workload is the desired placement of one container on one node. Every field
// except Observed is intent; Observed is what the node's agent reported.
type Workload struct {
	ID          string `json:"id"`
	Name        string `json:"name"`
	Image       string `json:"image"`
	CPUMillis   int64  `json:"cpu_millis"`
	MemoryBytes int64  `json:"memory_bytes"`
	NodeID      string `json:"node_id"`
	// DesiredState is DesiredRunning (the default) or DesiredStopped.
	DesiredState string `json:"desired_state"`
	// ServiceID, ServiceRevision and ReplicaIndex (1-based) are set together
	// for a replica of a service and are all zero for a standalone workload.
	ServiceID       string    `json:"service_id,omitempty"`
	ServiceRevision int       `json:"service_revision,omitempty"`
	ReplicaIndex    int       `json:"replica_index,omitempty"`
	CreatedAt       time.Time `json:"created_at"`
	UpdatedAt       time.Time `json:"updated_at"`

	// Observed is the agent's latest report, or nil until it has made one. It
	// is read-only here: CreateWorkload ignores it, and only RecordObservations
	// writes it.
	Observed *Observation `json:"observed"`
}

// Phase is the workload's observed lifecycle phase: WorkloadScheduled until
// its agent has reported, then whatever it reported.
func (w Workload) Phase() string {
	if w.Observed == nil || w.Observed.State == "" {
		return WorkloadScheduled
	}
	return w.Observed.State
}

// prepareForCreate returns the workload as it will be stored, or ErrInvalid.
func (w Workload) prepareForCreate() (Workload, error) {
	if w.DesiredState == "" {
		w.DesiredState = DesiredRunning
	}
	w.Observed = nil
	w.CreatedAt = w.CreatedAt.UTC()
	if w.UpdatedAt.IsZero() {
		w.UpdatedAt = w.CreatedAt
	}
	w.UpdatedAt = w.UpdatedAt.UTC()
	switch {
	case w.ID == "" || w.Name == "" || w.NodeID == "" || w.Image == "":
		return w, fmt.Errorf("%w: a workload needs an id, name, image and node", ErrInvalid)
	case w.CPUMillis <= 0 || w.MemoryBytes <= 0:
		return w, fmt.Errorf("%w: cpu_millis and memory_bytes must be positive", ErrInvalid)
	case !ValidDesiredState(w.DesiredState):
		return w, fmt.Errorf("%w: desired state %q must be running or stopped", ErrInvalid, w.DesiredState)
	case w.ServiceRevision < 0 || w.ReplicaIndex < 0:
		return w, fmt.Errorf("%w: service revision and replica index must not be negative", ErrInvalid)
	case (w.ServiceID == "") != (w.ServiceRevision == 0) || (w.ServiceID == "") != (w.ReplicaIndex == 0):
		return w, fmt.Errorf("%w: service_id, service_revision and replica_index must be set together", ErrInvalid)
	}
	return w, nil
}

// Observation is what a node's agent reported about one workload's container:
// observed state. A workload has at most one, replaced by each newer report.
type Observation struct {
	WorkloadID   string     `json:"workload_id"`
	NodeID       string     `json:"node_id"` // the reporting node; set by RecordObservations
	State        string     `json:"state"`   // an observed phase, never WorkloadScheduled
	Message      string     `json:"message"`
	ContainerID  string     `json:"container_id,omitempty"`
	ExitCode     *int       `json:"exit_code,omitempty"`
	OOMKilled    bool       `json:"oom_killed"`
	RestartCount int        `json:"restart_count"`
	StartedAt    *time.Time `json:"started_at,omitempty"`
	FinishedAt   *time.Time `json:"finished_at,omitempty"`
	ObservedAt   time.Time  `json:"observed_at"` // when the manager received the report
}

// SameReport reports whether o says the same thing as the stored observation,
// ignoring who reported it and when, so callers can skip a write that would
// change nothing.
func (o Observation) SameReport(p Observation) bool {
	return o.State == p.State && o.Message == p.Message && o.ContainerID == p.ContainerID &&
		o.OOMKilled == p.OOMKilled && o.RestartCount == p.RestartCount &&
		equalPtr(o.ExitCode, p.ExitCode) && equalTimePtr(o.StartedAt, p.StartedAt) && equalTimePtr(o.FinishedAt, p.FinishedAt)
}

func equalPtr[T comparable](a, b *T) bool {
	if a == nil || b == nil {
		return a == b
	}
	return *a == *b
}

func equalTimePtr(a, b *time.Time) bool {
	if a == nil || b == nil {
		return a == b
	}
	return a.Equal(*b)
}

// ServiceSpec is what one revision of a service runs. It is desired state:
// nothing here has been applied to any container yet.
//
// The newer fields (Ports, HealthCheck, RestartPolicy) are omitted from the
// JSON when empty, so specs stored before they existed encode, and therefore
// hash, exactly as they did.
type ServiceSpec struct {
	Image         string            `json:"image"`
	Command       []string          `json:"command,omitempty"`
	Env           map[string]string `json:"env,omitempty"`
	CPUMillis     int64             `json:"cpu_millis"`
	MemoryBytes   int64             `json:"memory_bytes"`
	NodeSelector  map[string]string `json:"node_selector,omitempty"`
	Ports         []ServicePort     `json:"ports,omitempty"`
	HealthCheck   *HealthCheck      `json:"health_check,omitempty"`
	RestartPolicy *RestartPolicy    `json:"restart_policy,omitempty"`
}

// Restart conditions a RestartPolicy may name.
const (
	RestartNo        = "no"
	RestartOnFailure = "on-failure"
	RestartAlways    = "always"
)

// ServicePort exposes one container port. HostPort is the port to publish on
// the node, or 0 to let the node choose one; the address it is published on
// is the agent's decision (loopback unless the agent is configured otherwise).
type ServicePort struct {
	ContainerPort int    `json:"container_port"`
	Protocol      string `json:"protocol"` // "tcp" or "udp"
	HostPort      int    `json:"host_port,omitempty"`
}

// HealthCheck is a command run inside the container; exit status 0 means healthy.
type HealthCheck struct {
	// Command is in exec form (program and arguments, no shell).
	Command            []string `json:"command"`
	IntervalSeconds    int      `json:"interval_seconds"`
	TimeoutSeconds     int      `json:"timeout_seconds"`
	StartPeriodSeconds int      `json:"start_period_seconds"`
	Retries            int      `json:"retries"`
}

// RestartPolicy says when a replica that stopped is started again.
type RestartPolicy struct {
	Condition string `json:"condition"` // RestartNo, RestartOnFailure or RestartAlways
	// MaxRetries bounds restarts for RestartOnFailure; it is 0 for the others.
	MaxRetries int `json:"max_retries,omitempty"`
}

// Hash identifies the spec's content: equal specs hash equally, whatever the
// order of map keys.
func (s ServiceSpec) Hash() string {
	b, err := json.Marshal(s) // map keys are sorted, field order is fixed
	if err != nil {
		panic("store: cannot encode a service spec: " + err.Error())
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func (s ServiceSpec) validate() error {
	if s.Image == "" || s.CPUMillis <= 0 || s.MemoryBytes <= 0 {
		return fmt.Errorf("%w: a service spec needs an image and positive cpu_millis and memory_bytes", ErrInvalid)
	}
	return nil
}

// Service is the desired definition of a replicated workload: how many
// replicas to run and which revision of the spec they should run.
type Service struct {
	ID              string `json:"id"`
	Name            string `json:"name"`
	Replicas        int    `json:"replicas"`         // desired replica count
	CurrentRevision int    `json:"current_revision"` // desired deployment revision
	// Version increases with every change to the service and is the token
	// for optimistic locking.
	Version   int64      `json:"version"`
	CreatedAt time.Time  `json:"created_at"`
	UpdatedAt time.Time  `json:"updated_at"`
	DeletedAt *time.Time `json:"deleted_at,omitempty"`
}

// Definition is a service together with the revision it currently runs.
type Definition struct {
	Service  Service  `json:"service"`
	Revision Revision `json:"revision"`
}

// Revision is an immutable snapshot of a service's spec. Revision numbers
// start at 1 and only grow; rolling back deploys an old spec as a new revision.
type Revision struct {
	ServiceID string      `json:"service_id"`
	Revision  int         `json:"revision"`
	Spec      ServiceSpec `json:"spec"`
	SpecHash  string      `json:"spec_hash"`
	Message   string      `json:"message,omitempty"`
	CreatedBy string      `json:"created_by,omitempty"`
	CreatedAt time.Time   `json:"created_at"`
}

// NewService describes a service to create together with its first revision.
type NewService struct {
	ID        string
	Name      string
	Replicas  int
	Spec      ServiceSpec
	Message   string
	CreatedBy string
	At        time.Time
}

func (n NewService) validate() error {
	if n.ID == "" || !ValidName(n.Name) || n.Replicas < 0 {
		return fmt.Errorf("%w: a service needs an id, a valid name and a non-negative replica count", ErrInvalid)
	}
	return n.Spec.validate()
}

// Deployment describes a new revision of an existing service.
type Deployment struct {
	Spec            ServiceSpec
	Message         string
	CreatedBy       string
	ExpectedVersion int64
	At              time.Time
}

// Event is one entry of the administrative audit trail.
type Event struct {
	ID           int64             `json:"id"`
	At           time.Time         `json:"at"`
	InstanceID   string            `json:"instance_id,omitempty"` // the manager that recorded it
	Actor        string            `json:"actor"`
	Action       string            `json:"action"` // for example "service.created"
	ResourceType string            `json:"resource_type"`
	ResourceID   string            `json:"resource_id"`
	Message      string            `json:"message,omitempty"`
	Details      map[string]string `json:"details,omitempty"`
}

// EventFilter selects events. The zero value means the latest 100.
type EventFilter struct {
	ResourceType string
	ResourceID   string
	// BeforeID returns only events with a smaller ID; pass the last ID of a
	// page to get the next, older one.
	BeforeID int64
	// Limit is capped at MaxEventLimit; zero means DefaultEventLimit.
	Limit int
}

const (
	DefaultEventLimit = 100
	MaxEventLimit     = 1000
)

func (f EventFilter) limit() int {
	switch {
	case f.Limit <= 0:
		return DefaultEventLimit
	case f.Limit > MaxEventLimit:
		return MaxEventLimit
	}
	return f.Limit
}

// Lease is a named, time-limited claim by one manager. Token increases every
// time the lease changes hands, so a manager that lost its lease without
// noticing can be told apart from the current holder (a fencing token).
type Lease struct {
	Name      string    `json:"name"`
	Holder    string    `json:"holder"`
	Token     int64     `json:"token"`
	ExpiresAt time.Time `json:"expires_at"`
}

// NodeRepository stores nodes (observed state).
type NodeRepository interface {
	// UpsertNode inserts or updates a node. An existing node keeps its RegisteredAt.
	UpsertNode(ctx context.Context, n Node) (Node, error)
	// Heartbeat sets LastHeartbeat; it returns ErrNotFound for unknown nodes.
	Heartbeat(ctx context.Context, id string, at time.Time) error
	GetNode(ctx context.Context, id string) (Node, error)
	ListNodes(ctx context.Context) ([]Node, error)
}

// EnrollmentRepository stores enrollments (desired state).
type EnrollmentRepository interface {
	// CreateEnrollment enrolls a node ID. It returns ErrConflict while an
	// active enrollment exists; a revoked one is replaced (re-enrollment).
	CreateEnrollment(ctx context.Context, e Enrollment) (Enrollment, error)
	GetEnrollment(ctx context.Context, nodeID string) (Enrollment, error)
	ListEnrollments(ctx context.Context) ([]Enrollment, error)
	// RevokeEnrollment sets RevokedAt (keeping an earlier revocation time) and
	// returns ErrNotFound for a node that was never enrolled.
	RevokeEnrollment(ctx context.Context, nodeID string, at time.Time) (Enrollment, error)
}

// WorkloadRepository stores workload placements (desired state) and, apart
// from them, the observations agents report about those workloads.
type WorkloadRepository interface {
	// CreateWorkload returns ErrConflict for a duplicate ID, name or service
	// replica, ErrNotFound when the node or service revision does not exist,
	// and ErrInvalid for malformed values. w.Observed is ignored.
	CreateWorkload(ctx context.Context, w Workload) (Workload, error)
	// GetWorkload returns the workload with its observation.
	GetWorkload(ctx context.Context, id string) (Workload, error)
	// ListWorkloads returns every workload, with observations, ordered by name.
	ListWorkloads(ctx context.Context) ([]Workload, error)
	// ListWorkloadsForNode returns the workloads placed on nodeID, ordered by name.
	ListWorkloadsForNode(ctx context.Context, nodeID string) ([]Workload, error)
	// ListWorkloadsForService returns a service's replicas ordered by
	// revision and replica index.
	ListWorkloadsForService(ctx context.Context, serviceID string) ([]Workload, error)
	// SetWorkloadDesiredState changes the desired state. It never touches the
	// observation. Setting the current value changes nothing (ErrUnchanged).
	SetWorkloadDesiredState(ctx context.Context, id, desired string, at time.Time) (Workload, error)
	// RecordObservations stores agent reports, all or none. Reports for
	// workloads that do not exist or are placed on another node are ignored,
	// and so is a report older than the stored one (a late arrival). An
	// unknown state fails the whole batch with ErrInvalid.
	RecordObservations(ctx context.Context, nodeID string, obs []Observation) error
}

// ServiceRepository stores service definitions (desired state): the number
// of replicas wanted and the immutable revisions of what each should run.
//
// Every mutating call takes the version the caller read. A non-zero
// expectedVersion that no longer matches fails with ErrVersionConflict, so two
// managers (or an admin and a reconciler) cannot silently overwrite each other.
// Zero skips the check.
type ServiceRepository interface {
	// CreateService creates the service and its first revision atomically.
	// It returns ErrConflict for a duplicate ID or active name.
	CreateService(ctx context.Context, n NewService) (Service, error)
	// GetService returns a service by ID, including a deleted one.
	GetService(ctx context.Context, id string) (Service, error)
	// GetServiceByName returns the active (not deleted) service with that name.
	GetServiceByName(ctx context.Context, name string) (Service, error)
	// ListServices returns services ordered by name; deleted ones only on request.
	ListServices(ctx context.Context, includeDeleted bool) ([]Service, error)
	// ListDefinitions is ListServices with each service's current revision,
	// read in one query.
	ListDefinitions(ctx context.Context, includeDeleted bool) ([]Definition, error)
	// ScaleService sets the desired replica count (ErrUnchanged if equal).
	ScaleService(ctx context.Context, id string, replicas int, expectedVersion int64, at time.Time) (Service, error)
	// DeployService records a new revision and makes it current (ErrUnchanged
	// when the spec equals the current revision's).
	DeployService(ctx context.Context, id string, d Deployment) (Service, Revision, error)
	// DeleteService marks the service deleted and its desired replicas zero.
	// Its revisions and workloads are kept.
	DeleteService(ctx context.Context, id string, expectedVersion int64, at time.Time) (Service, error)
	GetRevision(ctx context.Context, serviceID string, revision int) (Revision, error)
	// ListRevisions returns a service's revisions, oldest first.
	ListRevisions(ctx context.Context, serviceID string) ([]Revision, error)
}

// EventRepository stores the administrative audit trail.
type EventRepository interface {
	// AppendEvent stores an event and returns it with its ID.
	AppendEvent(ctx context.Context, e Event) (Event, error)
	// ListEvents returns events newest first.
	ListEvents(ctx context.Context, f EventFilter) ([]Event, error)
}

// LeaseRepository stores named leases with fencing tokens, the building block
// for "only one manager does this" duties such as a reconciler. Managers
// pass their own clock, so they need synchronized clocks (NTP).
type LeaseRepository interface {
	// AcquireLease takes or renews a lease for holder until now+ttl. The same
	// holder renewing keeps its token; taking over a free or expired lease
	// increments the token. Another holder's unexpired lease fails with
	// ErrLeaseHeld.
	AcquireLease(ctx context.Context, name, holder string, ttl time.Duration, now time.Time) (Lease, error)
	// ReleaseLease ends the lease now if holder still holds it (ErrNotFound otherwise).
	ReleaseLease(ctx context.Context, name, holder string, now time.Time) error
	GetLease(ctx context.Context, name string) (Lease, error)
}

// Repositories is every repository. Inside a transaction they all see the
// same snapshot and commit or roll back together.
type Repositories interface {
	NodeRepository
	EnrollmentRepository
	WorkloadRepository
	ServiceRepository
	EventRepository
	LeaseRepository
}

// Tx is a transaction.
type Tx interface {
	Repositories
	// LockPlacement takes the cluster-wide placement lock until the
	// transaction ends. Placement reads all nodes and workloads and then
	// writes one, so two placements must not interleave, whether they run in
	// this manager or in another one sharing the database.
	LockPlacement(ctx context.Context) error
}

// Store is the whole persistence layer.
type Store interface {
	Repositories

	// InTx runs fn in a transaction: if fn returns an error every change it
	// made is rolled back, otherwise they are committed together. fn must use
	// tx, not the Store, and is never retried.
	InTx(ctx context.Context, fn func(tx Tx) error) error

	Ping(ctx context.Context) error
	Close()
}
