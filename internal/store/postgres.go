// placementLockID is the advisory lock behind Tx.LockPlacement.
const placementLockID int64 = 0x646f636b706c63

// dbtx is the part of a connection pool and of a transaction that the queries
// use, so one implementation serves both. Begin on a transaction creates a
// savepoint, so methods that need several statements to be atomic can start
// their own transaction whether or not the caller already has one.
type dbtx interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
	Begin(ctx context.Context) (pgx.Tx, error)
}

type queries struct {
	db dbtx
}

// atomic runs fn in a transaction, or a savepoint when already inside one.
func (q *queries) atomic(ctx context.Context, fn func(q *queries) error) error {
	tx, err := q.db.Begin(ctx)
	if err != nil {
		return fmt.Errorf("begin transaction: %w", err)
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(ctx)) }()
	if err := fn(&queries{db: tx}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("commit transaction: %w", err)
	}
	return nil
}

// Postgres is the PostgreSQL-backed Store. Any number of managers can share
// one database: nothing here keeps state in process, IDs are generated by the
// callers, uniqueness is enforced by constraints, and concurrent changes are
// guarded by optimistic versions, row locks and advisory locks.
type Postgres struct {
	*queries
	pool *pgxpool.Pool
}

var _ Store = (*Postgres)(nil)

// OpenPostgres connects to PostgreSQL and verifies the connection. It does not
// change the schema: call Migrate.
func OpenPostgres(ctx context.Context, url string) (*Postgres, error) {
	pool, err := pgxpool.New(ctx, url)
	if err != nil {
		return nil, fmt.Errorf("open postgres pool: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("ping postgres: %w", err)
	}
	return &Postgres{queries: &queries{db: pool}, pool: pool}, nil
}

// Migrate applies the embedded migrations that the database has not seen.
func (p *Postgres) Migrate(ctx context.Context) error {
	migrations, err := loadMigrations(migrationFS, "migrations")
	if err != nil {
		return err
	}
	return applyMigrations(ctx, p.pool, migrations)
}

func (p *Postgres) Ping(ctx context.Context) error {
	return p.pool.Ping(ctx)
}

func (p *Postgres) Close() {
	p.pool.Close()
}

type pgTx struct{ *queries }

var _ Tx = (*pgTx)(nil)

func (t *pgTx) LockPlacement(ctx context.Context) error {
	if _, err := t.db.Exec(ctx, `SELECT pg_advisory_xact_lock($1)`, placementLockID); err != nil {
		return fmt.Errorf("lock placement: %w", err)
	}
	return nil
}

// InTx runs fn in a read-committed transaction. Writers that must not
// interleave take LockPlacement or rely on versions and row locks.
func (p *Postgres) InTx(ctx context.Context, fn func(tx Tx) error) error {
	tx, err := p.pool.Begin(ctx)
	if err != nil {
		return fmt.Errorf("begin transaction: %w", err)
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(ctx)) }()
	if err := fn(&pgTx{queries: &queries{db: tx}}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("commit transaction: %w", err)
	}
	return nil
}

// mapError translates database errors into the store's sentinels.
func mapError(err error) error {
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) {
		switch pgErr.Code {
		case "23505":
			return fmt.Errorf("%w (%s)", ErrConflict, pgErr.ConstraintName)
		case "23503":
			return fmt.Errorf("%w (%s)", ErrNotFound, pgErr.ConstraintName)
		case "23514", "22P02":
			return fmt.Errorf("%w: %s", ErrInvalid, pgErr.Message)
		}
	}
	if errors.Is(err, pgx.ErrNoRows) {
		return ErrNotFound
	}
	return err
}

func nilIfZero[T comparable](v T) *T {
	var zero T
	if v == zero {
		return nil
	}
	return &v
}

func marshalJSON(v any) ([]byte, error) {
	b, err := json.Marshal(v)
	if err != nil {
		return nil, fmt.Errorf("encode json: %w", err)
	}
	return b, nil
}

// ---- nodes ----

const nodeColumns = `id, name, cpu_millis, memory_bytes, labels, agent_version, registered_at, last_heartbeat, health, health_since, deregistered_at`

func scanNode(row pgx.Row) (Node, error) {
	var n Node
	var labels []byte
	var deregistered *time.Time
	err := row.Scan(&n.ID, &n.Name, &n.CPUMillis, &n.MemoryBytes, &labels, &n.AgentVersion, &n.RegisteredAt, &n.LastHeartbeat, &n.Health, &n.HealthSince, &deregistered)
	if err != nil {
		return Node{}, mapError(err)
	}
	if deregistered != nil {
		n.DeregisteredAt = deregistered.UTC()
	}
	n.HealthSince = n.HealthSince.UTC()
	if err := json.Unmarshal(labels, &n.Labels); err != nil {
		return Node{}, fmt.Errorf("decode node labels: %w", err)
	}
	if n.Labels == nil {
		n.Labels = map[string]string{}
	}
	n.RegisteredAt = n.RegisteredAt.UTC()
	n.LastHeartbeat = n.LastHeartbeat.UTC()
	return n, nil
}

func (q *queries) UpsertNode(ctx context.Context, n Node) (Node, error) {
	labels, err := marshalJSON(cloneLabels(n.Labels))
	if err != nil {
		return Node{}, err
	}
	// A new node starts healthy; an existing one keeps the health state the
	// reconciler recorded, so the reconciler sees the recovery and reports it.
	return scanNode(q.db.QueryRow(ctx,
		`INSERT INTO nodes (`+nodeColumns+`)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'healthy', $7, NULL)
		 ON CONFLICT (id) DO UPDATE SET
		   name = EXCLUDED.name,
		   cpu_millis = EXCLUDED.cpu_millis,
		   memory_bytes = EXCLUDED.memory_bytes,
		   labels = EXCLUDED.labels,
		   agent_version = EXCLUDED.agent_version,
		   last_heartbeat = EXCLUDED.last_heartbeat,
		   deregistered_at = NULL
		 RETURNING `+nodeColumns,
		n.ID, n.Name, n.CPUMillis, n.MemoryBytes, labels, n.AgentVersion, n.RegisteredAt, n.LastHeartbeat))
}

func (q *queries) DeregisterNode(ctx context.Context, id string, at time.Time) error {
	tag, err := q.db.Exec(ctx, `UPDATE nodes SET last_heartbeat = $3, deregistered_at = $2 WHERE id = $1`, id, at.UTC(), time.Time{})
	if err != nil {
		return err
	}
	if tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

func (q *queries) SetNodeHealth(ctx context.Context, id, health string, at time.Time) error {
	if !ValidNodeHealth(health) {
		return fmt.Errorf("%w: node health %q must be healthy, suspect or unavailable", ErrInvalid, health)
	}
	tag, err := q.db.Exec(ctx, `UPDATE nodes SET health = $2, health_since = $3 WHERE id = $1`, id, health, at.UTC())
	if err != nil {
		return mapError(err)
	}
	if tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

func (q *queries) Heartbeat(ctx context.Context, id string, at time.Time) error {
	tag, err := q.db.Exec(ctx, `UPDATE nodes SET last_heartbeat = $2 WHERE id = $1`, id, at)
	if err != nil {
		return err
	}
	if tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

func (q *queries) GetNode(ctx context.Context, id string) (Node, error) {
	return scanNode(q.db.QueryRow(ctx, `SELECT `+nodeColumns+` FROM nodes WHERE id = $1`, id))
}

func (q *queries) ListNodes(ctx context.Context) ([]Node, error) {
	rows, err := q.db.Query(ctx, `SELECT `+nodeColumns+` FROM nodes ORDER BY id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Node{}
	for rows.Next() {
		n, err := scanNode(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, n)
	}
	return out, rows.Err()
}

// ---- enrollments ----

const enrollmentColumns = `node_id, description, created_at, revoked_at`

func scanEnrollment(row pgx.Row) (Enrollment, error) {
	var e Enrollment
	if err := row.Scan(&e.NodeID, &e.Description, &e.CreatedAt, &e.RevokedAt); err != nil {
		return Enrollment{}, mapError(err)
	}
	e.CreatedAt = e.CreatedAt.UTC()
	e.RevokedAt = utcPtr(e.RevokedAt)
	return e, nil
}

func (q *queries) CreateEnrollment(ctx context.Context, e Enrollment) (Enrollment, error) {
	// The WHERE clause lets only a revoked enrollment be replaced; for an
	// active one no row comes back, which is reported as a conflict.
	created, err := scanEnrollment(q.db.QueryRow(ctx,
		`INSERT INTO enrollments (node_id, description, created_at)
		 VALUES ($1, $2, $3)
		 ON CONFLICT (node_id) DO UPDATE SET
		   description = EXCLUDED.description,
		   created_at = EXCLUDED.created_at,
		   revoked_at = NULL
		 WHERE enrollments.revoked_at IS NOT NULL
		 RETURNING `+enrollmentColumns,
		e.NodeID, e.Description, e.CreatedAt))
	if errors.Is(err, ErrNotFound) {
		return Enrollment{}, ErrConflict
	}
	return created, err
}

func (q *queries) GetEnrollment(ctx context.Context, nodeID string) (Enrollment, error) {
	return scanEnrollment(q.db.QueryRow(ctx, `SELECT `+enrollmentColumns+` FROM enrollments WHERE node_id = $1`, nodeID))
}

func (q *queries) ListEnrollments(ctx context.Context) ([]Enrollment, error) {
	rows, err := q.db.Query(ctx, `SELECT `+enrollmentColumns+` FROM enrollments ORDER BY node_id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Enrollment{}
	for rows.Next() {
		e, err := scanEnrollment(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, e)
	}
	return out, rows.Err()
}

func (q *queries) RevokeEnrollment(ctx context.Context, nodeID string, at time.Time) (Enrollment, error) {
	return scanEnrollment(q.db.QueryRow(ctx,
		`UPDATE enrollments SET revoked_at = COALESCE(revoked_at, $2) WHERE node_id = $1 RETURNING `+enrollmentColumns,
		nodeID, at))
}
